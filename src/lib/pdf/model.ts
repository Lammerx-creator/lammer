export type Version = 'questions' | 'answers';
export type Mode = 'card' | 'de-ru' | 'ru-de' | 'input' | 'cloze' | 'sentence' | 'grammar';
export const modes: Mode[] = ['card','de-ru','ru-de','input','cloze','sentence','grammar'];
export type Word = {id:string;lemma:string;pos:string;article:string;plural:string;verbForms:string;translation:string;review:number|boolean;difficulty:string;note:string;frequency:number;reps?:number;due?:number;contexts?:Context[]};
export type Context = {text:string;forms:string[];name:string;version:Version;doc:string;page:number;section:string};
export type Document = {id:string;name:string;version:Version;pages:number};
export type StoredDocument = Document & {blob:Blob};
export type Page = {number:number;section:string;raw:string;fragments:string[]};
export type Fragment = {id:string;text:string;safe:boolean};
export type Source = {id:string;fragment:string;doc:string;page:number;ordinal:number;section:string};
export type WordFragment = {id:string;word:string;fragment:string;forms:string[];count:number};
export type Progress = {word:string;reps:number;interval:number;ease:number;due:number};
export type Attempt = {id:string;word:string;mode:Mode;answer:string;correct:0|1;created:number};
export type Stats = {words:number;reviewed:number;learned:number;due:number;today:number;correct:number;attempts:number;fragments:number;occurrences:number;errors:(Attempt&{lemma:string})[]};
export type Quiz = {id:string;mode:Mode;prompt:string;tokens?:string[];source:{name:string;page:number;section:string};notice?:string};
export type Result = {correct?:boolean;expected:string;word:Word;next?:Progress;recorded?:boolean};
export type StoredQuiz = Quiz & {word:string;expected:string;revealed?:boolean;result?:Result;created:number};
export type Backup = {version:1;progress:Progress[];attempts:Attempt[]};
export type Filter = {section?:string;difficulty?:string;min?:number;q?:string;offset?:number};
